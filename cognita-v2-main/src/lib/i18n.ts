export function isSupportedLocale(input: string | null | undefined): input is Locale {
  return !!input && SUPPORTED_LOCALES.includes(input as Locale)
}

export function getStoredLocale(): Locale {
  if (typeof window === 'undefined') return DEFAULT_LOCALE
  const stored = window.localStorage.getItem(STORAGE_KEY)
  if (isSupportedLocale(stored)) return stored
  return DEFAULT_LOCALE
}

export function setStoredLocale(locale: Locale) {
  if (typeof window === 'undefined') return
  window.localStorage.setItem(STORAGE_KEY, locale)
  window.dispatchEvent(new CustomEvent('cognita-language-changed', { detail: { locale } }))
}

export function t(locale: Locale, key: string): string {
  const loc = dictionary[locale] || dictionary[DEFAULT_LOCALE]
  const english = dictionary.en
  const fallback = dictionary[DEFAULT_LOCALE]
  const value = loc[key] ?? english[key] ?? fallback[key]
  if (typeof value === 'string') return value
  return key
}
